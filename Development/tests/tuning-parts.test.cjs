const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const c=vm.createContext({});vm.runInContext(fs.readFileSync('Development/tuning-parts.js','utf8').replaceAll('export ',''),c);
const run=s=>vm.runInContext(s,c);
run('var state=createTuningRun();var catalog=[{id:"a",name:"A",levels:[{damage:10},{damage:20},{damage:30}],sellCredits:[10,20,30]},{id:"b",name:"B",levels:[{damage:1},{damage:2},{damage:3}],sellCredits:[10,20,30]}]');
assert.equal(run('rollTuningPart(state,{type:"mob"},()=>1,catalog)'),null);
assert.equal(run('rollTuningPart(state,{type:"yuuka"},()=>.99,catalog).id'),'b');
assert.equal(run('rollTuningPart(state,{type:"mob"},()=>0,catalog).id'),'a');
assert(run('equipTuningPart(state,{id:"a",level:1},0).ok'));
assert.equal(run('equipTuningPart(state,{id:"a",level:1},1).ok'),false);
assert.equal(run('equipTuningPart(state,{id:"b",level:1},3).ok'),false);
assert(run('strengthenTuningPart(state,{id:"b",level:3},0)'));assert.equal(run('state.equipped[0].level'),2);
assert.equal(run('eligibleTuningParts(state,catalog).length'),0);
assert(run('strengthenTuningPart(state,{id:"c",level:1},0)'));assert.equal(run('state.equipped[0].level'),3);
assert.equal(run('strengthenTuningPart(state,{id:"d",level:1},0)'),false);
assert.equal(run('tuningPerk(state,"damage",catalog)'),30);
assert.equal(run('tuningSellValue(state.equipped[0],{stageCoinMultiplier:2,moneyUpBonus:50},catalog)'),90);
assert.equal(run('tuningSellValue({id:"unknown",level:1},{},catalog)'),null);
assert.equal(run('equipTuningPart(state,{id:"b",level:2},0).previous.level'),3);
assert.equal(run('state.equipped[0].level'),2);
console.log('PASS: normal/Yuuka rolls, three slots, duplicate prevention, swap-level retention, exclusions, max3, one-level consumption and sale multipliers.');
